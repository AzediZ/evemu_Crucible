def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def text_digest(path):
    """(size, sha256) of a repo text file with CRLF read as LF, as git stores it (checkouts differ in line ends)"""
    with open(path, 'rb') as f:
        data = f.read()
    if not path.endswith('.gz'):
        data = data.replace(b'\r\n', b'\n')
    return len(data), hashlib.sha256(data).hexdigest()


def fmt(v, kind):
    if kind == 'i':
        return str(int(v))
    x = float(v)
    if not math.isfinite(x):
        raise ValueError('non-finite value %r' % v)
    s = ('%.6g' if kind == 'f' else '%.10g') % x
    return '0' if s in ('-0', '0') else s


def table_rows(cal):
    rows = {}
    rows['mktCalType'] = [tuple(getattr(cal.types[t], c) for c, _ in TABLES[0][1]) for t in sorted(cal.types)]
    rows['mktCalRegion'] = [(r, t) + cal.region_rows[(r, t)] for (r, t) in sorted(cal.region_rows)]
    rows['mktCalRegionDefault'] = [(r,) + cal.region_default[r] for r in sorted(cal.region_default)]
    rows['mktCalGroup'] = [(g,) + cal.group_rows[g] for g in sorted(cal.group_rows)]
    rows['mktCalMeta'] = [k + cal.meta_rows[k] for k in sorted(cal.meta_rows)]
    rows['mktCalLoss'] = [k + (cal.loss_rows[k],) for k in sorted(cal.loss_rows)]
    rows['mktCalFit'] = [k + cal.fit_rows[k] for k in sorted(cal.fit_rows)]
    return rows


def write_sql(path, rows, comment):
    out = io.StringIO()
    w = out.write
    w(HEADER + ', change the generator and run it again\n')
    w('-- ' + ATTRIBUTION + '\n')
    for line in comment:
        w('-- ' + line + '\n')
    w('-- +migrate Up\n')
    for name, cols in TABLES:
        rs = rows[name]
        w('\n-- %s: %d rows\n' % (name, len(rs)))
        for i in range(0, len(rs), ROWS_PER_INSERT):
            chunk = rs[i:i + ROWS_PER_INSERT]
            w('INSERT INTO %s (%s) VALUES\n' % (name, ', '.join(c for c, _ in cols)))
            for j, r in enumerate(chunk):
                w('(' + ', '.join(fmt(v, k) for v, (_, k) in zip(r, cols)) + ')')
                w(';\n' if j == len(chunk) - 1 else ',\n')
    w('\n-- +migrate Down\n')
    for name, _ in reversed(TABLES):
        w('DELETE FROM %s;\n' % name)
    data = out.getvalue()
    for line in data.split('\n'):
        assert len(line) < 60000, 'line too long'
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(data)
    return data


def read_client_types(client):
    import evemarshal
    p = os.path.join(client, 'bulkdata', '600004.cache2')
    obj = evemarshal.load_file(p)
    cols, rows = evemarshal.table(obj)
    ci, cp, cm = cols.index('typeID'), cols.index('published'), cols.index('marketGroupID')
    return {r[ci]: (bool(r[cp]), r[cm] or 0) for r in rows}, p


def manifest(args, h, km, st, client_path, sql_path, sql_data):
    def log_of(folder):
        try:
            return fetch.load_log(folder)
        except (OSError, ValueError):
            return {}
    srcs = []
    hl = log_of(args.history)
    for f in h.files:
        e = hl.get(f['file'], {})
        srcs.append({'kind': 'market-history', 'file': f['file'], 'date': f['date'],
                     'url': e.get('url') or fetch.history_url(f['date']), 'lastModified': e.get('lastModified'),
                     'size': os.path.getsize(f['path']), 'sha256': sha256_file(f['path']), 'rows': f['rows'],
                     'rowsUsed': f['kept']})
    kl = log_of(args.killmails) if args.killmails else {}
    for f in km.files:
        e = kl.get(f['file'], {})
        srcs.append({'kind': 'killmails', 'file': f['file'], 'date': f['date'],
                     'url': e.get('url') or fetch.killmail_url(f['date']), 'lastModified': e.get('lastModified'),
                     'size': os.path.getsize(f['path']), 'sha256': sha256_file(f['path']), 'rows': f['rows']})
    static = []
    for s in st.sources:
        p = os.path.join(ROOT, 'sql', 'base', s) if s.endswith('.sql.gz') else os.path.join(ROOT, 'sql', 'migrations', s)
        rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
        size, digest = text_digest(p)
        static.append({'file': rel, 'size': size, 'sha256': digest})
    m = collections.OrderedDict()
    m['generator'] = 'utils/market-calibration/gen_market_calibration.py'
    m['attribution'] = ATTRIBUTION
    m['licence'] = ('No data licence is stated by EVE Ref (docs.everef.net/datasets); data.everef.net: "EVE Ref is the '
                    'property of Autonomous Logic. All rights reserved." plus the CCP hf. IP notice. Only derived '
                    'aggregates are committed; see utils/market-calibration/README.md.')
    m['window'] = {'from': args.first, 'to': args.last, 'days': len(h.days), 'daysWithData': len(h.present),
                   'missing': h.missing}
    m['killmailCoverage'] = args.killmail_coverage
    m['sources'] = srcs
    m['static'] = static
    if client_path:
        m['client'] = [{'file': 'bulkdata/600004.cache2', 'size': os.path.getsize(client_path),
                        'sha256': sha256_file(client_path)}]
    m['output'] = {'file': os.path.relpath(sql_path, ROOT).replace(os.sep, '/') if sql_path.startswith(ROOT) else
                   os.path.basename(sql_path),
                   'sha256': hashlib.sha256(sql_data.encode('utf-8')).hexdigest()}
    return m


def sources_digest(srcs):
    h = hashlib.sha256()
    for s in srcs:
        h.update(('%s %s\n' % (s['file'], s['sha256'])).encode('ascii'))
    return h.hexdigest()


def build_time_json(st, cal):
    """the market sim's phase 3 manufacturers (the harness snapshot):  the blueprint's productionTime per run (seconds,
    one run makes portionSize units) of every calibrated type that is built"""
    out = {}
    for t in sorted(st.bp):
        if t in cal.types and st.bp[t].get('productionTime'):
            out[str(t)] = int(st.bp[t]['productionTime'])
    return out


HAUL_GROUPS = (28, 380, 513)        # industrials, transport ships, freighters:  their cargo holds


def logistics_json(st, rows):
    """the market sim's phase 4 logistics (the harness snapshot):  k-space (systemID, security, regionID), its jumps
    (each once), the npc stations with a refinery (stationID, systemID, regionID, efficiency, take), the security bands
    each ore group's belts are in (bit 0 high-sec >= 0.45, 1 low-sec, 2 null-sec;  roidDistribution per securityClass),
    the hauling hulls' cargo holds and the regional node stations MarketSimDB::AutoRegionalStations picks (a high/low-sec
    region with 1% of the isk:  in its system with the most stations, the station with the most assembly lines)"""
    systems = {}
    for r in serverdata.load_synced('mapSolarSystems').rows:
        if r['regionID'] < 11000000:
            systems[r['solarSystemID']] = (float(r['security']), r['regionID'], r['securityClass'])
    jumps = sorted(set((min(r['fromSolarSystemID'], r['toSolarSystemID']), max(r['fromSolarSystemID'], r['toSolarSystemID']))
                       for r in serverdata.load_synced('mapSolarSystemJumps').rows
                       if r['fromSolarSystemID'] in systems and r['toSolarSystemID'] in systems))
    sta = serverdata.load_synced('staStations').rows
    stations = sorted((r['stationID'], r['solarSystemID'], r['regionID'], float(r['reprocessingEfficiency'] or 0),
                       float(r['reprocessingStationsTake'] or 0))
                      for r in sta if (r['reprocessingEfficiency'] or 0) > 0 and r['solarSystemID'] in systems)
    by_class = collections.defaultdict(int)
    for sec, _region, cls in systems.values():
        by_class[cls] |= 1 if sec >= 0.45 else (2 if sec > 0 else 4)
    bands = collections.defaultdict(int)
    for r in serverdata.load_synced('roidDistribution').rows:
        if r['roidID'] in st.types:
            bands[st.types[r['roidID']]['groupID']] |= by_class.get(r['systemSec'], 0)
    cargo = dict((str(t), float(r['capacity'] or 0)) for t, r in sorted(st.types.items())
                 if r['groupID'] in HAUL_GROUPS and (r['capacity'] or 0) > 0)
    # the regional nodes:  as the server's 'auto'
    lines = collections.defaultdict(int)
    for r in serverdata.load_synced('ramAssemblyLineStations').rows:
        lines[r['stationID']] += r['quantity'] or 0
    isk = dict((r[0], r[3]) for r in rows['mktCalRegionDefault'])
    regional = []
    for region in sorted(isk):
        secs = [sec for sec, reg, _ in systems.values() if reg == region]
        if not secs or max(secs) <= 0.0 or isk[region] < 0.01:
            continue
        per = collections.Counter(r['solarSystemID'] for r in sta if r['regionID'] == region)
        if not per:
            continue
        top = sorted(per.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
        best = sorted((r['stationID'] for r in sta if r['solarSystemID'] == top), key=lambda sid: (-lines[sid], sid))[0]
        regional.append([region, best])
    return {'systems': [[sid, sec, reg] for sid, (sec, reg, _) in sorted(systems.items())],
            'jumps': [list(j) for j in jumps], 'stations': [list(s) for s in stations],
            'oreBands': dict((str(g), b) for g, b in sorted(bands.items())), 'cargo': cargo, 'regional': regional}


def chains_json(st, cal):
    """the market sim's phase 6 chains (the harness snapshot), as the server loads them (MarketSimDB::LoadChains):
    invention recipes (a T2 blueprint with a chanceOfRE, invented from its T1 parent's blueprint:  the activity 8
    datacores, the data interface's decryptor group;  the interface is not used up), decryptors, reactions
    (invTypeReactions x moonMiningAmount), planetary schematics, the bills of T2, T3 and components (per unit:  base
    materials less the recycled T1 item's, extras x damagePerJob, the blueprint's wasteFactor) and T2 blueprints"""
    import serverdata
    attrs = collections.defaultdict(dict)
    for r in serverdata.load_synced('dgmTypeAttributes').rows:
        if r['attributeID'] in (726, 1112, 1113, 1114, 1115, 1124):
            v = r['valueFloat'] if r['valueFloat'] is not None else r['valueInt']
            if v is not None:
                attrs[r['typeID']][r['attributeID']] = float(v)
    amounts = {t: a[726] for t, a in attrs.items() if a.get(726, 0) > 0}
    bps = {}
    for r in sorted(serverdata.load_synced('invBlueprintTypes').rows, key=lambda r: r['blueprintTypeID']):
        bps[r['blueprintTypeID']] = r
    reqs8 = collections.defaultdict(list)
    for r in serverdata.load_synced('ramTypeRequirements').rows:
        if r['activityID'] == 8:
            reqs8[r['typeID']].append(r)
    out = {'recipes': [], 'bills': {}, 'blueprints': {}, 'decryptors': [], 'moonAmounts': {}, 'materials': {}}

    def int_or_float(x):
        return int(x) if float(x).is_integer() else float(x)

    # bills and T2 blueprints (the lowest blueprint of each product, as derive.Static.bp)
    for t in sorted(st.bp):
        if t not in cal.types or cal.types[t].simClass not in (derive.MFG_T2, derive.MFG_T3, derive.COMPONENT):
            continue
        b = st.bp[t]
        portion = float(st.portion(t))
        base = collections.OrderedDict(st.mats.get(t, []))
        extra = []
        for req, q, dmg, rec in st.reqs.get(b['blueprintTypeID'], []):
            if req not in st.types or st.cat(req) == derive.CAT_SKILL:
                continue
            if rec:
                for m, mq in st.mats.get(req, []):
                    if m in base:
                        base[m] = max(0, base[m] - mq * q)
            if dmg > 0:
                extra.append([req, q * dmg / portion])
        base_l = [[m, q / portion] for m, q in base.items() if q > 0]
        if base_l or extra:
            out['bills'][str(t)] = {'base': base_l, 'extra': extra, 'wasteFactor': float(b['wasteFactor'] or 0) / 100.0}
        # what it reprocesses into (invTypeMaterials, as the server's reprocessing gives;  'bom' has the waste in)
        if st.mats.get(t):
            out['materials'][str(t)] = [[m, q / portion] for m, q in st.mats[t]]
        if cal.types[t].simClass == derive.MFG_T2:
            out['blueprints'][str(t)] = b['blueprintTypeID']
    # invention
    for bp2 in sorted(bps):
        b2 = bps[bp2]
        if not (b2['chanceOfRE'] and b2['chanceOfRE'] > 0):
            continue
        parent, meta = st.meta.get(b2['productTypeID'], (None, None))
        if meta != 2 or parent not in st.bp:
            continue
        b1 = st.bp[parent]
        inputs, group = [], 0
        for r in sorted(reqs8.get(b1['blueprintTypeID'], []), key=lambda r: r['requiredTypeID']):
            req = r['requiredTypeID']
            if req not in st.types or st.cat(req) == derive.CAT_SKILL:
                continue
            if st.group(req) == GROUP_DATA_INTERFACE:
                group = int(attrs.get(req, {}).get(1115, 0))
                continue
            q = (r['quantity'] or 0) * float(r['damagePerJob'] or 0)
            if q > 0:
                inputs.append([req, int_or_float(q)])
        if not inputs:
            continue
        t1max, t2max = max(1, int(b1['maxProductionLimit'] or 1)), max(1, int(b2['maxProductionLimit'] or 1))
        runs = min(max(int(math.floor(t2max / 10.0)), 1), t2max)     # EvEMath::RAM::InventionRuns, a max-run T1 copy
        out['recipes'].append({'kind': 1, 'id': b1['blueprintTypeID'], 'inputs': inputs, 'outputs': [[bp2, runs]],
                               'seconds': float(b1['researchTechTime'] or 0), 'chance': float(b2['chanceOfRE']),
                               'decryptorGroup': group, 'maxRuns': t2max})
    # decryptors
    for t in sorted(attrs):
        a = attrs[t]
        if not any(k in a for k in (1112, 1113, 1114, 1124)) or t not in cal.types:
            continue
        out['decryptors'].append([t, st.group(t), a.get(1112, 1.0), a.get(1124, 0.0), a.get(1113, 0.0), a.get(1114, 0.0)])
    # reactions and schematics

    def amount(t):
        return max(1.0, amounts.get(t, 1.0))
    reactions = collections.OrderedDict()
    for r in sorted(serverdata.load_synced('invTypeReactions').rows, key=lambda r: (r['reactionTypeID'], r['input'], r['typeID'])):
        e = reactions.setdefault(r['reactionTypeID'], {'kind': 2, 'id': r['reactionTypeID'], 'inputs': [], 'outputs': [],
                                                       'seconds': 3600.0, 'chance': 1.0, 'decryptorGroup': 0, 'maxRuns': 0})
        e['inputs' if r['input'] else 'outputs'].append([r['typeID'], int_or_float((r['quantity'] or 0) * amount(r['typeID']))])
    out['recipes'] += [e for e in reactions.values() if e['inputs'] and e['outputs']]
    cycle = {r['schematicID']: float(r['cycleTime'] or 0) for r in serverdata.load_synced('piSchematics').rows}
    schematics = collections.OrderedDict()
    for r in sorted(serverdata.load_synced('piTypeMap').rows, key=lambda r: (r['schematicID'], r['typeID'])):
        e = schematics.setdefault(r['schematicID'], {'kind': 3, 'id': r['schematicID'], 'inputs': [], 'outputs': [],
                                                     'seconds': cycle.get(r['schematicID'], 0.0), 'chance': 1.0,
                                                     'decryptorGroup': 0, 'maxRuns': 0})
        flag = r['isInput']
        is_input = (ord(flag) if isinstance(flag, str) else int(flag or 0)) != 0
        e['inputs' if is_input else 'outputs'].append([r['typeID'], r['quantity'] or 0])
    out['recipes'] += [e for e in schematics.values() if e['inputs'] and e['outputs'] and e['seconds'] > 0]
    out['moonAmounts'] = {str(t): amounts[t] for t in sorted(amounts)}
    return out


def export_json(path, st, cal, rows):
    types = {}
    for t in sorted(cal.types):
        r = st.types[t]
        b = st.bp.get(t)
        types[str(t)] = {'name': r['typeName'], 'groupID': r['groupID'], 'categoryID': st.cat(t),
                         'portionSize': st.portion(t), 'volume': float(r['volume'] or 0),
                         'basePrice': st.base_price(t), 'metaGroupID': st.meta.get(t, (None, None))[1],
                         'parentTypeID': st.meta.get(t, (None, None))[0],
                         'techLevel': st.tech(t) or None, 'blueprintTypeID': b['blueprintTypeID'] if b else None}
    bom, refine = {}, {}
    for t in sorted(st.bp):
        if t in cal.types:
            base, extra = st.bom_lines(t)
            bom[str(t)] = {'portion': st.portion(t), 'base': base, 'extra': extra}
    for t in sorted(st.mats):
        if t not in st.bp and t in cal.types:
            refine[str(t)] = {'portion': st.portion(t), 'materials': st.mats[t]}
    cal_json = {name: {'columns': [c for c, _ in cols], 'rows': rows[name]} for name, cols in TABLES}
    doc = {'generator': 'utils/market-calibration/gen_market_calibration.py', 'attribution': ATTRIBUTION,
           'types': types, 'bom': bom, 'refine': refine, 'calibration': cal_json}
    doc['buildTime'] = build_time_json(st, cal)
    doc['logistics'] = logistics_json(st, rows)
    doc['chains'] = chains_json(st, cal)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(doc, f, sort_keys=True, separators=(',', ':'))
        f.write('\n')


# ---------------------------------------------------------------- consistency report
class Report(object):
    def __init__(self):
        self.lines = []
        self.failed = []

    def __call__(self, s=''):
        self.lines.append(s)

    def check(self, ok, text):
        self('  [%s] %s' % ('PASS' if ok else 'FAIL', text))
        if not ok:
            self.failed.append(text)


def report(st, h, km, cal, rows, args):
    R = Report()
    N = cal.N
    R('== inputs')
    R('  window %s .. %s: %d days, %d with a market-history file%s' % (
        args.first, args.last, len(h.days), N, ', missing: ' + ' '.join(h.missing) if h.missing else ''))
    R('  rows read %d, used %d;  dropped %s' % (sum(f['rows'] for f in h.files), sum(f['kept'] for f in h.files),
                                               dict(sorted(h.dropped.items()))))
    R('  type IDs unknown to the client: %d (top: %s)' % (len(h.unknown_types), ', '.join(
        '%d x%d' % (t, n) for t, n in sorted(h.unknown_types.items(), key=lambda kv: (-kv[1], kv[0]))[:5])))
    R('  traded types that are not market types (no client marketGroupID): %d' % len(h.nonmarket_types))
    if h.date_mismatch:
        R('  rows whose date differs from the file date: %d' % h.date_mismatch)
    if km.days:
        R('  killmails: %d archives, %d killmails (%.0f/day);  by band %s;  npc-only %.1f%%;  dropped %s' % (
            km.days, km.count, km.count / km.days,
            {['high', 'low', 'null', 'w-space'][b]: '%.0f%%' % (100.0 * n / km.count) for b, n in sorted(km.bands.items())},
            100.0 * km.npc_only / max(1, km.count), dict(sorted(km.dropped.items()))))
    else:
        R('  killmails: none (no --killmails folder):  mktCalLoss/mktCalFit empty, consumeShare from category defaults')
    if st.client_diff is not None:
        d = st.client_diff
        R('  client bulkdata vs synced server data: types only in client %d, only in server %d, market types only in '
          'client %d, only in server %d' % (len(d['onlyClient']), len(d['onlyServer']), len(d['marketOnlyClient']),
                                            len(d['marketOnlyServer'])))

    R('\n== coverage per class (types, refPrice > 0, by price source)')
    by = collections.defaultdict(list)
    for r in cal.types.values():
        by[r.simClass].append(r)
    for c in sorted(by):
        rs = by[c]
        src = collections.Counter(derive.SOURCE_NAMES[r.priceSource] for r in rs)
        R('  %2d %-27s %5d  priced %5d  %s' % (c, derive.CLASS_NAMES[c], len(rs), sum(1 for r in rs if r.refPrice > 0),
                                              ', '.join('%s %d' % kv for kv in sorted(src.items()))))
    nonex = [r for r in cal.types.values() if r.simClass != derive.EXCLUDED]
    priced = sum(1 for r in nonex if r.refPrice > 0)
    R('  market types %d, excluded (PLEX, Apparel) %d, non-excluded %d, with refPrice > 0: %d (%.2f%%)' % (
        len(cal.types), len(by[derive.EXCLUDED]), len(nonex), priced, 100.0 * priced / max(1, len(nonex))))
    R.check(priced >= 0.99 * len(nonex), 'coverage: at least 99% of non-excluded market types have refPrice > 0')
    nosim = sorted(r.typeID for r in by[derive.NOT_SIM] if r.refPrice <= 0)
    if nosim:
        R('  no price at all (players only): %s' % ', '.join('%d %s' % (t, st.name(t)) for t in nosim[:15]))
    R.check(all(r.refPrice > 0 for r in nonex if r.simClass != derive.NOT_SIM), 'no simulated type with refPrice <= 0')
    vend = [r for r in cal.types.values() if r.simClass == derive.VENDOR]
    below = [r for r in vend if r.refPrice < st.base_price(r.typeID) - 1e-6]
    R.check(not below, 'no NPC-vendor type below basePrice (%d vendor types)' % len(vend))

    R('\n== spot checks (PLAN.md Phase 1)')
    trit = cal.types[34].refPrice
    R.check(3.5 <= trit <= 5.0, 'Tritanium refPrice %.3f in [3.5, 5.0]' % trit)
    raven = cal.types[638]
    mc = math.fsum(q * cal.types[m].refPrice for m, q in st.mats[638])
    R.check(abs(raven.refPrice / mc - 1) <= 0.10, 'Raven refPrice %.4g within 10%% of its mineral cost %.4g (ratio %.3f;'
            ' buildCostRef at ME 0 %.4g, ratio %.3f)' % (raven.refPrice, mc, raven.refPrice / mc, raven.buildCostRef,
                                                         raven.refPrice / raven.buildCostRef))
    for r in history.HUBS[1:]:
        ratios = [v[0] for (rr, t), v in cal.region_rows.items() if rr == r and (rr, t) in cal.cell_ratio]
        m = median(ratios)
        R.check(0.95 <= m <= 1.05, '%s priceRatio median %.3f in [0.95, 1.05] (%d types;  region default %.3f, '
                'IQR %.3f-%.3f)' % (st.regions[r], m, len(ratios), cal.region_default[r][0], percentile(ratios, .25),
                                     percentile(ratios, .75)))

    R('\n== region shares (ISK, top 12) and default price ratios')
    for r in sorted(cal.region_default, key=lambda r: (-cal.region_default[r][2], r))[:12]:
        pr, us, isk = cal.region_default[r]
        R('  %-16s isk %.3f  units %.3f  priceRatio %.3f  cells %d' % (
            st.regions[r], isk, us, pr, sum(1 for (rr, _) in cal.region_rows if rr == r)))

    R('\n== mineral volume implied by Forge final-good volumes (BOM recursion) vs observed Forge mineral volume')
    need = collections.Counter()
    memo = {}

    def per_unit(t, depth=0):
        if t in memo:
            return memo[t]
        out = collections.Counter()
        if t in st.bp and depth < 8:
            base, extra = st.bom_lines(t)
            for m, q in base + extra:
                if m in derive.MINERALS:
                    out[m] += q / st.portion(t)
                elif m in st.bp:
                    for mm, qq in per_unit(m, depth + 1).items():
                        out[mm] += q * qq / st.portion(t)
        memo[t] = out
        return out
    final = (derive.CAT_SHIP, derive.CAT_MODULE, derive.CAT_CHARGE, derive.CAT_DRONE, derive.CAT_STRUCTURE,
             derive.CAT_SUBSYSTEM)
    for t in sorted(cal.types):
        if st.cat(t) in final and t in st.bp:
            c = cal.by_type.get(t, {}).get(history.FORGE)
            if c is not None:
                u = sum(c.vol) / N
                for m, q in per_unit(t).items():
                    need[m] += u * q
    for m in derive.MINERALS:
        c = cal.by_type.get(m, {}).get(history.FORGE)
        obs = sum(c.vol) / N if c is not None else 0
        R('  %-10s implied %12.4g/day  observed %12.4g/day  ratio %.2f' % (st.name(m), need[m], obs,
                                                                          need[m] / obs if obs else float('nan')))

    R('\n== T1 price / BOM (ME 0 waste, Forge history types) and price / raw mineral cost, per category')
    rat = collections.defaultdict(list)
    rawr = collections.defaultdict(list)
    for t in sorted(cal.types):
        r = cal.types[t]
        if r.simClass != derive.MFG_T1 or r.priceSource != derive.SRC_HISTORY or not r.buildCostRef:
            continue
        if cal.hist[t]['kind'] != 'forge':
            continue
        rat[st.cat(t)].append(r.refPrice / r.buildCostRef)
        if all(m in derive.MINERALS for m, _ in st.mats.get(t, [])) and st.mats.get(t):
            raw = math.fsum(q * cal.types[m].refPrice for m, q in st.mats[t]) / st.portion(t)
            rawr[st.cat(t)].append(r.refPrice / raw)
    for c in sorted(rat, key=lambda c: -len(rat[c])):
        xs = rat[c]
        if len(xs) >= 5:
            ys = rawr.get(c, [])
            R('  %-22s n=%4d  price/BOM median %.2f IQR %.2f-%.2f   price/minerals n=%d median %s' % (
                st.cats[c], len(xs), median(xs), percentile(xs, .25), percentile(xs, .75), len(ys),
                '%.2f' % median(ys) if ys else '-'))
    R('  cost markups (price/BOM) used for gap filling:  ' + ', '.join(
        '%s T%d %.2f' % (st.cats.get(k[1], k[1]), k[2], v) for k, v in sorted(cal.markup_by.items(), key=str)
        if k[0] == 'c'))

    R('\n== meta variants:  median price ratio to the parent (all categories)')
    R('  ' + ', '.join('meta %d: %.3g (units %.3g)' % (k[0], v[0], v[1]) for k, v in sorted(cal.meta_rows.items())
                       if k[1] == 0))
    R('  named meta-level fits (groups): %d' % len(cal.named_fit))

    R('\n== volatility (%d-day horizon, per sqrt(day);  derive.horizon_volatility), Forge-history types, per category;'
      '  1-day MAD for comparison' % derive.VOL_LAG)
    vc = collections.defaultdict(list)
    for t in sorted(cal.types):
        r = cal.types[t]
        c = cal.by_type.get(t, {}).get(history.FORGE)
        if r.simClass in (derive.EXCLUDED, derive.NOT_SIM) or c is None or cal.hist[t]['kind'] != 'forge':
            continue
        one = derive.horizon_volatility(c.day, c.avg, lag=1)
        vc[st.cat(t)].append((r.volatility, derive.clip(one, derive.VOL_MIN, derive.VOL_MAX) if one is not None else None))
    for c in sorted(vc, key=lambda c: -len(vc[c])):
        xs = [v for v, _ in vc[c]]
        ones = [o for _, o in vc[c] if o is not None]
        if len(xs) >= 20:
            R('  %-24s n=%5d  median %.4f  p90 %.4f  at the %.3f floor %4.1f%%   (1-day: median %.4f, at the floor %4.1f%%)' % (
                st.cats[c], len(xs), median(xs), percentile(xs, .9), derive.VOL_MIN,
                100.0 * sum(1 for x in xs if x <= derive.VOL_MIN) / len(xs), median(ones),
                100.0 * sum(1 for x in ones if x <= derive.VOL_MIN) / max(1, len(ones))))

    R('\n== consumeShare and elasticity, median per category (simulated types)')
    cc = collections.defaultdict(list)
    for r in cal.types.values():
        if r.simClass not in (derive.EXCLUDED, derive.NOT_SIM):
            cc[st.cat(r.typeID)].append(r)
    for c in sorted(cc, key=lambda c: -len(cc[c])):
        rs = cc[c]
        R('  %-24s n=%5d  consumeShare %.3f  elasticity %.2f  killmail-based %d' % (
            st.cats[c], len(rs), median([r.consumeShare for r in rs]), median([r.elasticity for r in rs]),
            sum(1 for r in rs if r.typeID in cal.km_consume)))
    if km.days:
        sl = math.fsum(n for t, n in km.hull.items() if st.cat(t) == derive.CAT_SHIP) / km.days
        su = math.fsum(r.unitsPerDay for r in cal.types.values() if st.cat(r.typeID) == derive.CAT_SHIP)
        R('  public ship losses %.0f/day vs all-region ship units %.0f/day (ratio %.2f);  capsules %.0f/day' % (
            sl, su, sl / su if su else 0, km.hull.get(670, 0) / km.days))
        R('  mktCalLoss %d rows (%d victim types), mktCalFit %d rows (%d hulls)' % (
            len(cal.loss_rows), len(set(k[0] for k in cal.loss_rows)), len(cal.fit_rows),
            len(set(k[0] for k in cal.fit_rows))))
        for hull in (24698, 587, 638, 670):
            items = sorted(((q, t) for (hh, t), (q, _) in cal.fit_rows.items() if hh == hull), reverse=True)[:6]
            R('    %-10s %s' % (st.name(hull), ', '.join('%s x%.2f' % (st.name(t), q) for q, t in items)))

    R('\n== weekday multipliers (Mon..Sun), all groups by ISK;  sources %s' % dict(sorted(cal.weekday_source.items())))
    wds = [v[-7:] for v in cal.group_rows.values()]
    R('  median ' + ' '.join('%.3f' % median([w[i] for w in wds]) for i in range(7)))

    R('\n== top movers between the window halves (Forge median, types with >= 20 days each half, >= 1e8 ISK/day)')
    half = h.days[len(h.days) // 2]
    mv = []
    for t in sorted(cal.types):
        c = cal.by_type.get(t, {}).get(history.FORGE)
        if c is None:
            continue
        a = [p for d, p in zip(c.day, c.avg) if h.days[d] < half]
        b = [p for d, p in zip(c.day, c.avg) if h.days[d] >= half]
        if len(a) >= 20 and len(b) >= 20 and cal.types[t].refPrice * cal.types[t].unitsPerDay >= 1e8:
            mv.append((median(b) / median(a), t))
    mv.sort()
    R('  down: ' + ', '.join('%s %.2f' % (st.name(t), x) for x, t in mv[:10]))
    R('  up:   ' + ', '.join('%s %.2f' % (st.name(t), x) for x, t in mv[::-1][:10]))

    R('\n== table rows:  ' + ', '.join('%s %d' % (n, len(rows[n])) for n, _ in TABLES))
    if R.failed:
        R('\nFAILED: ' + '; '.join(R.failed))
    return R


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--history', required=True)
    ap.add_argument('--killmails')
    ap.add_argument('--client')
    ap.add_argument('--from', dest='first', default='2011-12-01')
    ap.add_argument('--to', dest='last', default='2012-05-21')
    ap.add_argument('--killmail-coverage', type=float, default=0.5)
    ap.add_argument('--out', default=DEFAULT_OUT)
    ap.add_argument('--manifest', default=DEFAULT_MANIFEST)
    ap.add_argument('--export-json')
    ap.add_argument('--summary')
    ap.add_argument('--strict', action='store_true')
    args = ap.parse_args()

    client_types, client_path = (read_client_types(args.client) if args.client else (None, None))
    st = derive.Static(client_types)
    h = history.read(args.history, args.first, args.last, st.known, st.market, set(st.regions))
    if not h.present:
        raise SystemExit('no market-history files for %s .. %s in %s' % (args.first, args.last, args.history))
    km_days = killmails.archive_days(args.killmails, args.first, args.last)
    km = killmails.read(args.killmails, km_days, st.known, st.systems)
    cal = derive.Calibration(st, h, km, args.killmail_coverage)
    rows = table_rows(cal)

    srcs = [{'file': f['file'], 'sha256': sha256_file(f['path'])} for f in h.files + km.files]
    comment = ['window %s .. %s (Crucible 1.0-1.6):  %d market-history days, %d killmail days (%d killmails)' % (
                   args.first, args.last, len(h.present), km.days, km.count),
               'sources: utils/market-calibration/manifest.json (sha256 of the source list %s)' % sources_digest(srcs),
               'rows: ' + ', '.join('%s %d' % (n, len(rows[n])) for n, _ in TABLES)]
    data = write_sql(args.out, rows, comment)
    man = manifest(args, h, km, st, client_path, os.path.abspath(args.out), data)
    with open(args.manifest, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(man, f, indent=1)
        f.write('\n')
    if args.export_json:
        export_json(args.export_json, st, cal, rows)
    R = report(st, h, km, cal, rows, args)
    text = '\n'.join(R.lines) + '\n'
    sys.stdout.write(text)
    if args.summary:
        with open(args.summary, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    if args.strict and R.failed:
        sys.exit(1)


if __name__ == '__main__':
    main()
