#!/usr/bin/env python3
"""
gen_missing_type_attributes.py - builds the migration that gives the types the database has no dogma attributes for
(npc entities, deadspace overseers, police drones, celestial structures and containers, ...) their attributes and
effects from the Crucible client's own bulkdata.

    python -I utils/type-attributes/gen_missing_type_attributes.py --attrs <800006.cache2|csv>
                                                                    [--effects <800007.cache2|csv>] [--out <file.sql>]

--attrs     the client's dgmTypeAttributes bulkdata (bulkdata/800006.cache2), or a csv of it (value,typeID,attributeID)
--effects   the client's dgmTypeEffects bulkdata (bulkdata/800007.cache2), or a csv of it (typeID,effectID,isDefault)

Repo data:  invTypes, dgmAttributeTypes, dgmEffects, dgmTypeAttributes and dgmTypeEffects from sql/base (.sql.gz dumps)
plus the rows the Up sections of sql/migrations insert into those tables (except this generator's own output).
Only types that are in invTypes and have no rows at all in the repo's table get rows, so types that already have
attributes (or effects) are never touched.  Attributes / effects the database does not define are left out.
Values go to valueInt or valueFloat the way the repo stores that attribute (most of its rows);  non-integral values
always go to valueFloat.  The output is deterministic.  Stdlib only.
"""

import argparse
import collections
import gzip
import io
import math
import os
import re
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BASE = os.path.join(ROOT, 'sql', 'base')
MIGRATIONS = os.path.join(ROOT, 'sql', 'migrations')
DEFAULT_OUT = os.path.join(MIGRATIONS, '20261011150000-type-attributes-missing.sql')

HEADER = '-- generated by utils/type-attributes/gen_missing_type_attributes.py'
INT_MIN, INT_MAX = -2 ** 31, 2 ** 31 - 1


def parse_values(s, i):
    """the rows of one INSERT ... VALUES list starting at s[i]"""
    rows = []
    n = len(s)
    while i < n:
        while i < n and s[i] in ' ,\n\r\t':
            i += 1
        if i >= n or s[i] != '(':
            break
        i += 1
        row = []
        while True:
            while s[i] in ' \n\r\t':
                i += 1
            if s[i] == "'":
                i += 1
                buf = []
                while True:
                    c = s[i]
                    if c == '\\':
                        nx = s[i + 1]
                        buf.append({'0': '\0', 'n': '\n', 'r': '\r', 't': '\t'}.get(nx, nx))
                        i += 2
                    elif c == "'":
                        if i + 1 < n and s[i + 1] == "'":
                            buf.append("'")
                            i += 2
                        else:
                            i += 1
                            break
                    else:
                        buf.append(c)
                        i += 1
                row.append(''.join(buf))
            else:
                j = i
                while s[j] not in ',)':
                    j += 1
                tok = s[i:j].strip()
                i = j
                if tok.upper() == 'NULL':
                    row.append(None)
                else:
                    try:
                        row.append(int(tok))
                    except ValueError:
                        try:
                            row.append(float(tok))
                        except ValueError:
                            row.append(tok)
            while s[i] in ' \n\r\t':
                i += 1
            if s[i] == ',':
                i += 1
                continue
            if s[i] == ')':
                i += 1
                break
        rows.append(row)
    return rows


def insert_rows(data, table, cols):
    """rows (dicts) of every INSERT INTO <table> in data;  cols is the table's column order when an insert has no list"""
    out = []
    pat = r'INSERT\s+(?:IGNORE\s+)?INTO\s+`?%s`?\s*(\([^)]*\))?\s*VALUES\s*' % table
    for im in re.finditer(pat, data, re.I):
        names = cols
        if im.group(1):
            names = [c.strip().strip('`') for c in im.group(1)[1:-1].split(',')]
        for row in parse_values(data, im.end()):
            if len(row) == len(names):
                out.append(dict(zip(names, row)))
    return out


def load_base(name):
    """list of dicts (column -> value) from sql/base/<name>.sql.gz"""
    data = gzip.open(os.path.join(BASE, name + '.sql.gz'), 'rt', encoding='utf-8', errors='replace').read()
    m = re.search(r'CREATE TABLE `%s` \((.*?)\n\)' % name, data, re.S)
    cols = re.findall(r'^\s+`(\w+)`', m.group(1), re.M)
    return cols, insert_rows(data, name, cols)


def load_migrations(tables):
    """table -> rows inserted by the Up sections of sql/migrations, leaving out the ones this script wrote"""
    out = collections.defaultdict(list)
    for fn in sorted(os.listdir(MIGRATIONS)):
        if not fn.endswith('.sql'):
            continue
        text = open(os.path.join(MIGRATIONS, fn), encoding='utf-8', errors='replace').read()
        if text.startswith(HEADER):
            continue
        up = re.split(r'^\s*--\s*\+migrate\s+Down', text, flags=re.M | re.I)[0]
        up = re.sub(r'^\s*--.*$', '', up, flags=re.M)
        for table, cols in tables.items():
            out[table].extend(insert_rows(up, table, cols))
    return out


def rle(buf, size):
    """the zero-run encoding of a packed row's data"""
    out = bytearray(size + 8)
    oi = i = 0
    nib = False
    run = 0
    while i < len(buf):
        nib = not nib
        if nib:
            run = buf[i]
            i += 1
            cnt = (run & 0x0f) - 8
        else:
            cnt = (run >> 4) - 8
        if cnt >= 0:
            oi += cnt + 1
        else:
            while cnt and i < len(buf):
                out[oi] = buf[i]
                oi += 1
                i += 1
                cnt += 1
    return bytes(out)


def read_cache2(path, fmt):
    """the packed rows (CRowset of saved descriptor 1) of a client bulkdata file, unpacked with fmt (size order)"""
    data = open(path, 'rb').read()
    fmt = '<' + fmt
    need = struct.calcsize(fmt)
    rows = []
    p = 0
    while True:
        p = data.find(b'\x2a\x1b\x01', p)
        if p < 0:
            break
        n = data[p + 3]
        if n == 0xff:
            n = struct.unpack_from('<I', data, p + 4)[0]
            start = p + 8
        else:
            start = p + 4
        rows.append(struct.unpack_from(fmt, rle(data[start:start + n], need), 0))
        p = start + n
    return rows


def read_client(path, fmt):
    if path.lower().endswith('.cache2'):
        return read_cache2(path, fmt)
    rows = []
    for line in open(path, encoding='utf-8'):
        line = line.strip()
        if line:
            rows.append(tuple(float(x) if '.' in x or 'e' in x.lower() else int(x) for x in line.split(',')))
    return rows


def fmt_float(v):
    if v == int(v) and abs(v) < 1e15:
        return str(int(v))
    return repr(float(v))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--attrs', required=True, help='client 800006.cache2 (dgmTypeAttributes) or its csv')
    ap.add_argument('--effects', help='client 800007.cache2 (dgmTypeEffects) or its csv')
    ap.add_argument('--out', default=DEFAULT_OUT)
    args = ap.parse_args()

    type_cols, types = load_base('invTypes')
    type_names = {r['typeID']: r['typeName'] for r in types}
    attr_cols, base_attrs = load_base('dgmTypeAttributes')
    eff_cols, base_effs = load_base('dgmTypeEffects')
    attr_defs = {r['attributeID'] for r in load_base('dgmAttributeTypes')[1]}
    eff_defs = {r['effectID'] for r in load_base('dgmEffects')[1]}
    mig = load_migrations({'dgmTypeAttributes': attr_cols, 'dgmTypeEffects': eff_cols, 'invTypes': type_cols})
    for r in mig['invTypes']:
        type_names.setdefault(r['typeID'], r.get('typeName', ''))

    # which column the repo stores each attribute in
    kind = collections.defaultdict(lambda: [0, 0])
    has_attrs = set()
    for r in base_attrs + mig['dgmTypeAttributes']:
        has_attrs.add(r['typeID'])
        if r.get('valueInt') is not None:
            kind[r['attributeID']][0] += 1
        elif r.get('valueFloat') is not None:
            kind[r['attributeID']][1] += 1
    has_effects = {r['typeID'] for r in base_effs + mig['dgmTypeEffects']}

    # client dgmTypeAttributes:  (value R8, typeID I4, attributeID I4)
    attr_rows = {}
    skipped_attrs = collections.Counter()
    for value, type_id, attr_id in read_client(args.attrs, 'dii'):
        if type_id not in type_names or type_id in has_attrs:
            continue
        if attr_id not in attr_defs or not math.isfinite(value):
            skipped_attrs[attr_id] += 1
            continue
        attr_rows[(type_id, attr_id)] = value
    attr_types = sorted({t for t, _ in attr_rows})

    eff_rows = {}
    skipped_effs = collections.Counter()
    if args.effects:
        # client dgmTypeEffects:  (typeID I4, effectID I4, isDefault bit)
        for type_id, effect_id, flags in read_client(args.effects, 'iiB'):
            if type_id not in type_names or type_id in has_effects:
                continue
            if effect_id not in eff_defs:
                skipped_effs[effect_id] += 1
                continue
            eff_rows[(type_id, effect_id)] = flags & 1
    eff_types = sorted({t for t, _ in eff_rows})

    out = io.StringIO()
    w = out.write
    w(HEADER + ' from the Crucible client bulkdata\n')
    w('--  (800006 dgmTypeAttributes, 800007 dgmTypeEffects).  Do not edit:  change the generator and run it again.\n')
    w('-- %u types had no dgmTypeAttributes rows (%u rows here), %u types no dgmTypeEffects rows (%u rows here):\n'
      % (len(attr_types), len(attr_rows), len(eff_types), len(eff_rows)))
    w('--  npc entities (mission and deadspace npcs, overseers, police), celestial structures, containers, ...\n')
    w('-- +migrate Up\n')

    def insert(table, cols, rows, fmt):
        for i in range(0, len(rows), 500):
            w('INSERT INTO %s (%s) VALUES\n' % (table, ', '.join(cols)))
            w(',\n'.join(fmt(r) for r in rows[i:i + 500]))
            w(';\n')

    def attr_row(key):
        value = attr_rows[key]
        ints, floats = kind.get(key[1], (0, 0))
        integral = value == int(value) and INT_MIN <= value <= INT_MAX
        if integral and (ints > floats or not (ints or floats)):
            return '(%u, %u, %d, NULL)' % (key[0], key[1], int(value))
        return '(%u, %u, NULL, %s)' % (key[0], key[1], fmt_float(value))

    insert('dgmTypeAttributes', ['typeID', 'attributeID', 'valueInt', 'valueFloat'], sorted(attr_rows), attr_row)
    if eff_rows:
        insert('dgmTypeEffects', ['typeID', 'effectID', 'isDefault'], sorted(eff_rows),
               lambda k: '(%u, %u, %u)' % (k[0], k[1], eff_rows[k]))

    w('\n-- +migrate Down\n')

    def delete(table, ids):
        for i in range(0, len(ids), 200):
            w('DELETE FROM %s WHERE typeID IN (%s);\n' % (table, ','.join(str(t) for t in ids[i:i + 200])))

    delete('dgmTypeAttributes', attr_types)
    delete('dgmTypeEffects', eff_types)

    with open(args.out, 'w', newline='\n', encoding='utf-8') as f:
        f.write(out.getvalue())

    no_attrs = sorted(t for t in type_names if t not in has_attrs)
    print('wrote %s' % args.out)
    print('invTypes %u, without attribute rows %u, of those in the client %u' % (len(type_names), len(no_attrs),
                                                                                 len(attr_types)))
    print('dgmTypeAttributes: %u types, %u rows' % (len(attr_types), len(attr_rows)))
    print('dgmTypeEffects:    %u types, %u rows (%u of them among the attribute types)'
          % (len(eff_types), len(eff_rows), len(set(eff_types) & set(attr_types))))
    if skipped_attrs:
        print('client attributes not in dgmAttributeTypes (skipped): %s' % dict(sorted(skipped_attrs.items())))
    if skipped_effs:
        print('client effects not in dgmEffects (skipped): %s' % dict(sorted(skipped_effs.items())))


if __name__ == '__main__':
    main()
