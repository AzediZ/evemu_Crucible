-- Incursions, part 2: sites the way the EVE University wiki describes them
--  * incSiteObjects gets rooms (the beacon grid and the pockets behind acceleration gates), a role for
--    each object (wave ship, free ship, objective, respawning group, scenery, gate, container, asteroid),
--    a parameter and a name.  every site is re-laid out from its wiki page
--  * incIncursions remembers whether the mothership is out and whether a headquarters site has been run
--    at zero influence; incLPPool holds the LP paid when the mothership dies
--  * the Battletower (Central Bastion) and Mobile Headquarters (True Power Assembly Security HQ) objectives
--    get stationary, unarmed stats; the shield transfer control tower and communications array go back to
--    being containers; the site containers get container attributes
--  * remote repair range for the Mara, Intaki and the motherships, and the motherships' ECM burst range

-- +migrate Up

ALTER TABLE incSiteObjects
  ADD COLUMN room TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '0 = beacon grid, 1+ = pockets behind acceleration gates' AFTER siteTypeID,
  ADD COLUMN role TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Incursion::Role in IncursionMgr.h' AFTER wave,
  ADD COLUMN param INT NOT NULL DEFAULT 0 COMMENT 'gate: destination room.  respawn: seconds.  asteroid: units' AFTER quantity,
  ADD COLUMN itemName VARCHAR(100) NOT NULL DEFAULT '' COMMENT 'empty = the type name' AFTER param,
  MODIFY COLUMN wave TINYINT UNSIGNED NOT NULL COMMENT 'ships: wave number, 254 = mining spawn, 255 = scripted.  gates and containers: see Incursion::Role';
ALTER TABLE incIncursions
  ADD COLUMN hasBoss TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'the mothership site is up',
  ADD COLUMN hqRun TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'a headquarters site was completed at zero influence';
CREATE TABLE IF NOT EXISTS incLPPool (
  incursionID INT UNSIGNED NOT NULL,
  characterID INT UNSIGNED NOT NULL,
  lp INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'CONCORD LP earned in this incursion, paid when the mothership dies',
  PRIMARY KEY (incursionID, characterID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;

