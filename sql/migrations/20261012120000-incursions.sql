CREATE TABLE IF NOT EXISTS incSiteObjects (
  objectID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  siteTypeID SMALLINT UNSIGNED NOT NULL,
  wave TINYINT UNSIGNED NOT NULL COMMENT '0 = structures present for the whole site, 1+ = NPC waves',
  typeID INT UNSIGNED NOT NULL,
  quantity TINYINT UNSIGNED NOT NULL DEFAULT 1,
  x DOUBLE NOT NULL DEFAULT 0 COMMENT 'offset from the site beacon, metres',
  y DOUBLE NOT NULL DEFAULT 0,
  z DOUBLE NOT NULL DEFAULT 0,
  PRIMARY KEY (objectID),
  KEY siteTypeID (siteTypeID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;
CREATE TABLE IF NOT EXISTS incIncursions (
  incursionID INT UNSIGNED NOT NULL AUTO_INCREMENT,
